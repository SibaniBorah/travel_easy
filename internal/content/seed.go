// SeedIfEmpty populates the store with initial data if the states collection is empty.
func SeedIfEmpty(store *db.Store) error {
	states, err := store.ListStates()
	if err != nil {
		return err
	}
	if len(states) > 0 {
		return nil // already seeded
	}
	return seed(store)
}

func now() time.Time { return time.Now() }
func expires(days int) time.Time { return time.Now().AddDate(0, 0, days) }

func seed(store *db.Store) error {
	if err := seedStates(store); err != nil {
		return err
	}
	if err := seedDestinations(store); err != nil {
		return err
	}
	if err := seedRouteLegs(store); err != nil {
		return err
	}
	if err := seedPermitRules(store); err != nil {
		return err
	}
	if err := seedEvents(store); err != nil {
		return err
	}
	if err := seedBudgetEstimates(store); err != nil {
		return err
	}
	return nil
}

